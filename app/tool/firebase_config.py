#!/usr/bin/env python3
"""Turns google-services.json into the Android resources Firebase reads.

This replaces Google's Gradle plugin (which only does this conversion), so
the build has no extra plugin to keep compatible with new Android tooling.

    python3 tool/firebase_config.py < google-services.json

The JSON comes from the GOOGLE_SERVICES_JSON secret in CI and is never
committed. Without it the app builds normally and push notifications are
simply off. The output file is ignored by git.
"""
import json
import sys
from xml.sax.saxutils import escape

PACKAGE = "iq.wasla.messenger"
OUT = "android/app/src/main/res/values/firebase_config.xml"


def main() -> int:
    raw = sys.stdin.read().strip()
    if not raw:
        print("firebase_config: no google-services.json given; push stays off")
        return 0
    data = json.loads(raw)
    project = data["project_info"]
    client = next(
        (c for c in data["client"]
         if c["client_info"]["android_client_info"]["package_name"] == PACKAGE),
        None,
    )
    if client is None:
        print(f"firebase_config: no Android app {PACKAGE} in google-services.json", file=sys.stderr)
        return 1
    api_key = client["api_key"][0]["current_key"]
    values = {
        "google_app_id": client["client_info"]["mobilesdk_app_id"],
        "gcm_defaultSenderId": project["project_number"],
        "project_id": project["project_id"],
        "google_api_key": api_key,
        "google_crash_reporting_api_key": api_key,
        "google_storage_bucket": project.get("storage_bucket", ""),
    }
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by tool/firebase_config.py. Do not commit. -->",
             '<resources xmlns:tools="http://schemas.android.com/tools" tools:keep="@string/google_app_id,@string/gcm_defaultSenderId,@string/project_id,@string/google_api_key,@string/google_crash_reporting_api_key,@string/google_storage_bucket">']
    for k, v in values.items():
        if v:
            lines.append(f'    <string name="{k}" translatable="false">{escape(str(v))}</string>')
    lines.append("</resources>")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"firebase_config: wrote {OUT} for project {project['project_id']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
